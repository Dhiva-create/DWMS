// Helper to generate realistic historical control graph points
export function generateInitialControlPoints(): ControlDataPoint[] {
  const points: ControlDataPoint[] = [];

  // Generate Daily points for the last 20 days for key KPIs
  initialKPIs.forEach((kpi) => {
    // 1. Daily points (last 90 days to support 1 month, 2 months, 3 months cadences)
    for (let i = 90; i >= 1; i--) {
      const date = new Date(2026, 9, 5); // Current: Oct 5, 2026
      date.setDate(date.getDate() - i);
      const dateLabel = date.toLocaleDateString('en-US', {
        month: 'short',
        day: 'numeric',
      });
      // Fluctuation around centerLine
      const noise = (Math.sin(i * 0.7) + Math.cos(i * 1.3)) * 0.45;
      const spread = (kpi.ucl - kpi.lcl) * 0.16;
      let val = (kpi.centerLine ?? kpi.target) + noise * spread;

      // Ensure some natural outliers occasionally to demonstrate SPC out-of-control rules
      let remarks: string | undefined = undefined;
      if (i === 4 && kpi.id === 'kpi_inc_1') {
        val = 88.5; // Exceeds UCL
        remarks = 'High volume OT discharges simultaneous peak; 2 TPA portal timeouts';
      } else if (i === 22 && kpi.id === 'kpi_inc_1') {
        val = 86.2;
        remarks = 'System network latency during afternoon discharge surge';
      } else if (i === 11 && kpi.id === 'kpi_sup_1') {
        val = 5;
        remarks = 'MRD consultant signature delay on 3 surgical files';
      } else if (i === 8 && kpi.id === 'kpi_ins_2') {
        val = 98.0;
        remarks = 'TPA server maintenance downtime between 14:00 - 15:30';
      }

      val = Math.max(0, Number(val.toFixed(1)));

      points.push({
        id: `pt_d_${kpi.id}_${i}`,
        kpiId: kpi.id,
        periodType: 'Daily',
        label: dateLabel,
        timestamp: date.toISOString().split('T')[0],
        value: val,
        operatorName: 'Hospital HIS Automated Feed',
        remarks,
      });
    }

    // 2. Weekly points (last 12 weeks)
    for (let w = 12; w >= 1; w--) {
      const label = `Wk ${41 - w}`;
      const noise = (Math.cos(w * 1.5) + Math.sin(w * 0.8)) * 0.4;
      const spread = (kpi.ucl - kpi.lcl) * 0.14;
      const val = Math.max(
        0,
        Number(((kpi.centerLine ?? kpi.target) + noise * spread).toFixed(1))
      );
      points.push({
        id: `pt_w_${kpi.id}_${w}`,
        kpiId: kpi.id,
        periodType: 'Weekly',
        label,
        timestamp: `2026-W${41 - w}`,
        value: val,
        operatorName: 'Weekly DWM Audit Committee',
      });
    }

    // 3. Monthly points (last 24 months to support 12 months & 24 months windows)
    const months24 = [
      'Nov 24', 'Dec 24',
      'Jan 25', 'Feb 25', 'Mar 25', 'Apr 25', 'May 25', 'Jun 25',
      'Jul 25', 'Aug 25', 'Sep 25', 'Oct 25', 'Nov 25', 'Dec 25',
      'Jan 26', 'Feb 26', 'Mar 26', 'Apr 26', 'May 26', 'Jun 26',
      'Jul 26', 'Aug 26', 'Sep 26', 'Oct 26',
    ];
    months24.forEach((m, idx) => {
      const noise = Math.sin(idx * 0.9) * 0.35;
      const spread = (kpi.ucl - kpi.lcl) * 0.12;
      const val = Math.max(
        0,
        Number(((kpi.centerLine ?? kpi.target) + noise * spread).toFixed(1))
      );
      points.push({
        id: `pt_m_${kpi.id}_${idx}`,
        kpiId: kpi.id,
        periodType: 'Monthly',
        label: m,
        timestamp: `2025-${String((idx % 12) + 1).padStart(2, '0')}-01`,
        value: val,
        operatorName: 'Department Steering Review',
      });
    });

    // 4. Instance-based points (Last 50 batch instances / discharge cases)
    for (let ins = 50; ins >= 1; ins--) {
      const label = `Case #${1051 - ins}`;
      const noise = (Math.sin(ins * 0.9) + Math.cos(ins * 1.4)) * 0.45;
      const spread = (kpi.ucl - kpi.lcl) * 0.18;
      let val = (kpi.centerLine ?? kpi.target) + noise * spread;
      if (ins === 3 && kpi.id === 'kpi_csh_1') {
        val = 11.2; // Exceeds UCL of 9.5
      } else if (ins === 19 && kpi.id === 'kpi_inc_1') {
        val = 87.4;
      }
      val = Math.max(0, Number(val.toFixed(1)));
      points.push({
        id: `pt_ins_${kpi.id}_${ins}`,
        kpiId: kpi.id,
        periodType: 'Instance-based',
        label,
        timestamp: `2026-10-04T${10 + (ins % 8)}:${String((ins * 7) % 60).padStart(2, '0')}:00`,
        value: val,
        operatorName: 'Desk Counter Terminal',
      });
    }
  });

  return points;
}

export function generateInitialRoleSheetEntries(): RoleSheetEntry[] {
  const entries: RoleSheetEntry[] = [];
  let sNo = 1;

  initialPositions.forEach((pos) => {
    const posKpis = initialKPIs.filter((k) => k.positionId === pos.id);
    const posResps = initialResponsibilities.filter((r) => r.positionId === pos.id);

    posKpis.forEach((kpi, idx) => {
      const resp = posResps[idx] || posResps[0];
      entries.push({
        id: `rse_${pos.id}_${idx + 1}`,
        positionId: pos.id,
        sNo: sNo++,
        deptObjective: departmentInfo.objectiveText,
        roles: `${pos.displayNumber}. ${pos.title}`,
        kpi: `${kpi.code}: ${kpi.name}`,
        kpiId: kpi.id,
        direction: kpi.direction,
        target: kpi.target,
        uom: kpi.unit,
        frequency: kpi.measurementFrequency,
        operationalDefinition: kpi.calculationMethod,
        vcs: `Target: ${kpi.target} ${kpi.unit} | UCL: ${kpi.ucl} | LCL: ${kpi.lcl} | Checkpoint: ${resp?.verificationCheckpoint || 'Audit Stamp'}`,
        responsibility: resp ? `${resp.title}: ${resp.description}` : 'Daily operational routine oversight',
        priority: kpi.priority,
      });
    });
  });

  return entries;
}

